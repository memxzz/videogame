-- conf.lua
function love.conf(t)
    t.window.width = 800  -- Set your desired width
    t.window.height = 600  -- Set your desired height
    t.window.minwidth = 800     -- Minimum width in pixels
    t.window.minheight = 600    -- Minimum height in pixels
    t.window.resizable = true -- True if you want users to scale it manually
end
